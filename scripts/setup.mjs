#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

console.log('\n🔒 ====================================================');
console.log('   Edgekit Auth — Quick Setup Wizard');
console.log('====================================================\n');

const apiEnvPath = path.resolve(process.cwd(), 'apps/api/.dev.vars');
const rootEnvPath = path.resolve(process.cwd(), '.dev.vars');

if (!fs.existsSync(apiEnvPath) && !fs.existsSync(rootEnvPath)) {
  const generatedBetterAuthSecret = crypto.randomBytes(32).toString('hex');
  const generatedCookieSecret = crypto.randomBytes(32).toString('hex');

  const defaultEnv = `# Edgekit Auth - Local Development Environment
# Automatically generated by setup wizard

ENVIRONMENT=development
APP_URL=http://localhost:8787
BETTER_AUTH_URL=http://localhost:8787
BETTER_AUTH_SECRET=${generatedBetterAuthSecret}
COOKIE_SECRET=${generatedCookieSecret}

# Admin Bootstrapping (Comma-separated emails that receive 'admin' role automatically on signup)
ADMIN_EMAILS="admin@example.com"
`;

  fs.mkdirSync(path.dirname(apiEnvPath), { recursive: true });
  fs.writeFileSync(apiEnvPath, defaultEnv, 'utf-8');
  fs.writeFileSync(rootEnvPath, defaultEnv, 'utf-8');

  console.log('✅ File apps/api/.dev.vars created successfully!');
  console.log(`🔒 Generated Better Auth Secret: ${generatedBetterAuthSecret.slice(0, 10)}...`);
  console.log(`🔒 Generated Cookie Secret:      ${generatedCookieSecret.slice(0, 10)}...\n`);
} else {
  if (fs.existsSync(rootEnvPath) && !fs.existsSync(apiEnvPath)) {
    fs.mkdirSync(path.dirname(apiEnvPath), { recursive: true });
    fs.copyFileSync(rootEnvPath, apiEnvPath);
    console.log('✅ Synchronized .dev.vars to apps/api/.dev.vars\n');
  } else {
    console.log('ℹ️  File .dev.vars already exists. Preserving existing settings.\n');
  }
}

console.log('--- Recommended Next Steps ---');
console.log('1. Run local database migrations:');
console.log('   pnpm db:migrate:local\n');
console.log('2. Start local dev servers (Cloudflare Worker + Vite with instant HMR):');
console.log('   pnpm dev\n');
console.log('3. Access the interactive Web Dashboard:');
console.log('   http://localhost:5173 (Vite HMR)\n');
console.log('4. Create your first admin account via CLI:');
console.log('   pnpm admin:create --email admin@example.com --password secret --name "Admin"\n');
console.log('🚀 Done! Your serverless authentication engine is ready.\n');
